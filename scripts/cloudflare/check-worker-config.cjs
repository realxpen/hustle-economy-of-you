#!/usr/bin/env node
"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "../..");
const read = p => fs.readFileSync(path.join(root, p), "utf8");
const config = read("apps/web/cloudflare.config.ts");
const vite = read("apps/web/vite.config.ts");
const packageFile = JSON.parse(read("apps/web/package.json"));
const proxy = read("apps/web/lib/api/isolated-web-proxy.ts");
const auth = read("apps/web/lib/auth/isolated-web-auth.ts");
const manifest = read("apps/web/app/manifest.ts");
const legacyVercel = JSON.parse(read("apps/web/vercel.json"));
assert.match(config, /awsPreviewBuild \? "hustle-ios-pwa-aws-test" : "hustle-ios-pwa-staging"/);
assert.match(config, /HUSTLE_API_BACKEND_TARGET: bindings\.text/);
assert.match(config, /stagingAwsCutoverBuild/);
assert.match(config, /awsPreviewBuild \? "aws-lambda-isolated-staging" : "vercel-isolated-staging"/);
assert.match(config, /HUSTLE_STAGING_AWS_CUTOVER_BUILD === "true"/);
assert.match(config, /mutually exclusive/);
assert.match(config, /compatibilityFlags: \["nodejs_compat"\]/);
assert.match(config, /HUSTLE_ISOLATED_PWA_GATE: bindings\.text\(paymentPreviewBuild \? "payment-preview" : "isolated-staging"\)/);
assert.match(config, /paymentPreviewBuild \? "hustle-payment-preview"/);
assert.match(config, /HUSTLE_PAYMENT_PREVIEW_API_ORIGIN: bindings\.text/);
assert.match(config, /HUSTLE_PAYMENT_PREVIEW_BUILD === "true"/);
assert.match(config, /NEXT_PUBLIC_HUSTLE_WEB_STAGING_AUTH: bindings\.text\("true"\)/);
assert.match(config, /runWorkerFirst: awsPreviewBuild/);
assert.match(config, /"\!\/aws-test\.webmanifest"/);
assert.match(config, /: \["\/\*", "!\/_next\/static\/\*", "!\/\*\/_next\/static\/\*"\]/);
assert.doesNotMatch(config, /DATABASE_URL|BETTER_AUTH_SECRET|PAYSTACK|MONNIFY|SUPABASE_SERVICE_ROLE|AWS_SECRET/i);
assert.match(vite, /vinext\(/);
assert.match(vite, /cloudflare\(/);
assert.match(vite, /patchCssModules/);
assert.equal(packageFile.scripts["build:vinext"], "vite build");
assert.equal(packageFile.scripts["deploy:vinext"], "vinext-cloudflare deploy");
assert(packageFile.dependencies.vinext && packageFile.devDependencies.cf, "Pinned Cloudflare dependencies required");
assert.equal(legacyVercel.git.deploymentEnabled, false, "No Vercel auto deployments");
assert.match(proxy, /https:\/\/hustle-isolated-staging-api\.vercel\.app/);
assert.match(proxy, /isIsolatedWebPreviewEnabled/);
assert.match(proxy, /stagingProxyAllowed/);
assert.match(proxy, /"api\/v1\/auth\/sync"/);
assert.doesNotMatch(proxy, /const STAGING_API_ORIGIN = process\.env\./);
assert.match(auth, /endpoint = "\/api\/isolated\/auth\/"/);
assert.doesNotMatch(auth, /localStorage\.setItem|sessionStorage\.setItem/);
assert.match(manifest, /display: "standalone"/);
const release = read(".github/workflows/hustle-cloudflare-staging-deploy.yml");
assert.match(release, /workflow_dispatch:/);
assert.doesNotMatch(release, /^  push:|^  pull_request:/m);
assert.match(release, /CLOUDFLARE_API_TOKEN/);
assert.match(release, /CLOUDFLARE_ACCOUNT_ID/);
assert.match(release, /github\.ref/);
assert.match(release, /build:vinext/);
// A manual release previously failed because job-level NODE_ENV=production made
// npm ci omit build-time devDependencies (TS2307: vite-css-modules).
assert.match(release, /npm ci --include=dev/, "Cloudflare staging needs pinned development build tools");
assert(release.includes("npm ls vite-css-modules vite typescript --workspace=@hustle/web --depth=0"));
const cutover = read(".github/workflows/hustle-cloudflare-staging-aws-cutover.yml");
assert.match(cutover, /workflow_dispatch:/);
assert.doesNotMatch(cutover, /^  push:|^  pull_request:/m);
assert.match(cutover, /I_AUTHORIZE_AWS_STAGING_CUTOVER_ONLY/);
assert.match(cutover, /HUSTLE_STAGING_AWS_CUTOVER_BUILD: 'true'/);
assert.match(cutover, /environment: hustle-cloudflare-staging/);
assert.match(cutover, /test "\$HUSTLE_AWS_PREVIEW_BUILD" = "false"/);
const jobHeader = release.slice(release.indexOf("  build-and-deploy:"), release.indexOf("    steps:"));
assert(!/NODE_ENV: *production/.test(jobHeader), "Do not set production NODE_ENV before installing build tools");

console.log("PASS: Cloudflare Worker is isolated, pinned, nonfinancial and deploys only by explicit manual dispatch.");
