from copy import deepcopy
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import tempfile
import unittest

from backup_manifest import (EXTENSIONS, MAX_ARCHIVE, load_manifest, read_json,
                             validate_manifest, verify_local_set)
from seal_backup_set import seal


def fixture_draft():
    path = Path(__file__).parent / 'examples/backup-set.draft.json'
    value = json.loads(path.read_text())
    value['backup_set_id'] = 'hustle-synthetic-set'
    value['capture']['evidence_ref'] = 'synthetic-capture-only'
    for kind, extension in EXTENSIONS.items():
        value['archives'][kind]['filename'] = f'hustle-synthetic-set-{kind}{extension}'
    value['expected_counts'] = {
        'application': {'users': 2, 'services': 1, 'bookings': 3, 'notifications': 0},
        'auth': {'users': 2, 'identities': 2}, 'storage': {'buckets': 1, 'objects': 3}}
    return value


def sealed_fixture(root):
    value = fixture_draft()
    for kind, archive in value['archives'].items():
        # Opaque generated bytes only; these tests do not test encryption/decryption.
        (root / archive['filename']).write_bytes(b'synthetic-opaque-' + kind.encode())
    path, fingerprint = seal(value, root)
    return path, fingerprint, load_manifest(path.read_bytes(), fingerprint)


class BackupManifestTests(unittest.TestCase):
    def test_local_seal_and_verify_with_new_names_and_counts(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            path, fingerprint, manifest = sealed_fixture(root)
            self.assertEqual(verify_local_set(manifest, root), manifest)
            self.assertEqual(manifest['expected_counts']['storage']['objects'], 3)
            self.assertEqual(hashlib.sha256(path.read_bytes()).hexdigest(), fingerprint)
            for file in root.iterdir():
                if file.name.endswith(('.json', '.sha256')):
                    self.assertEqual(file.stat().st_mode & 0o777, 0o600)

    def test_manifest_pin_and_duplicate_json_fields_are_rejected(self):
        with tempfile.TemporaryDirectory() as directory:
            path, _, _ = sealed_fixture(Path(directory))
            with self.assertRaisesRegex(ValueError, 'fingerprint'):
                load_manifest(path.read_bytes() + b' ', '0' * 64)
        with self.assertRaisesRegex(ValueError, 'Duplicate JSON'):
            read_json(b'{"schema_version":1,"schema_version":1}')

    def test_operator_cli_seals_private_fixture_paths_with_spaces(self):
        with tempfile.TemporaryDirectory(prefix='hustle manifest ') as directory:
            root = Path(directory)
            draft = fixture_draft()
            for entry in draft['archives'].values():
                (root / entry['filename']).write_bytes(b'generated opaque fixture')
            source = root / 'draft.json'
            source.write_text(json.dumps(draft))
            script = Path(__file__).parent / 'seal_backup_set.py'
            result = subprocess.run([sys.executable, str(script), '--draft', str(source),
                                     '--directory', str(root)],
                                    env={'PATH': os.environ['PATH'], 'PYTHONDONTWRITEBYTECODE': '1'},
                                    capture_output=True, text=True, check=False)
            self.assertEqual(result.returncode, 0, result.stderr)
            fingerprint = re.search(r'Manifest SHA-256: ([a-f0-9]{64})', result.stdout).group(1)
            path = root / (draft['backup_set_id'] + '.manifest.json')
            self.assertEqual(hashlib.sha256(path.read_bytes()).hexdigest(), fingerprint)

    def test_invalid_manifest_metadata_is_rejected(self):
        with tempfile.TemporaryDirectory() as directory:
            _, _, baseline = sealed_fixture(Path(directory))
        cases = []
        def change(edit):
            value = deepcopy(baseline)
            edit(value)
            cases.append(value)
        change(lambda v: v.update(source_project_ref='a-different-project'))
        change(lambda v: v.update(password='must-never-be-in-a-manifest'))
        change(lambda v: v.update(schema_version=True))
        change(lambda v: v['archives'].pop('auth'))
        change(lambda v: v['archives']['application'].update(filename='../unsafe.enc'))
        change(lambda v: v['archives']['auth'].update(filename='other-set-auth.sql.gz.enc'))
        change(lambda v: v['archives']['auth'].update(captured_at='2026-10-19T12:59:59Z'))
        change(lambda v: v['archives']['auth'].update(size_bytes=MAX_ARCHIVE + 1))
        change(lambda v: v['archives']['auth'].update(sha256='not-a-hash'))
        change(lambda v: v['capture'].update(ended_at=v['capture']['started_at']))
        change(lambda v: v['capture'].update(consistency='not-frozen'))
        change(lambda v: v['capture'].update(evidence_ref='replace-with-actual-record'))
        change(lambda v: v['declared_coverage']['application'].remove('roles_grants'))
        change(lambda v: v['declared_coverage']['auth'].append('users'))
        change(lambda v: v['expected_counts']['storage'].update(objects=True))
        change(lambda v: v['expected_counts']['auth'].update(users=-1))
        for index, value in enumerate(cases):
            with self.subTest(case=index), self.assertRaises(ValueError):
                validate_manifest(value)

    def test_encrypted_byte_size_digest_and_checksum_changes_are_rejected(self):
        for modification in ('size', 'digest', 'sidecar'):
            with self.subTest(modification=modification), tempfile.TemporaryDirectory() as directory:
                root = Path(directory)
                _, _, manifest = sealed_fixture(root)
                archive = manifest['archives']['application']
                path = root / archive['filename']
                if modification == 'size':
                    path.write_bytes(path.read_bytes() + b'x')
                elif modification == 'digest':
                    path.write_bytes(b'x' * path.stat().st_size)
                else:
                    (root / (path.name + '.sha256')).write_text('0' * 64 + '  wrong.enc\n')
                with self.assertRaises(ValueError):
                    verify_local_set(manifest, root)

    def test_seal_refuses_symlink_input_or_conflicting_existing_checksum(self):
        for modification in ('symlink', 'checksum'):
            with self.subTest(modification=modification), tempfile.TemporaryDirectory() as directory:
                root = Path(directory)
                draft = fixture_draft()
                for entry in draft['archives'].values():
                    (root / entry['filename']).write_bytes(b'generated-fixture')
                path = root / draft['archives']['application']['filename']
                if modification == 'symlink':
                    path.unlink()
                    path.symlink_to(root / draft['archives']['auth']['filename'])
                else:
                    (root / (path.name + '.sha256')).write_bytes(b'conflicting-checksum')
                with self.assertRaises(ValueError):
                    seal(draft, root)
                self.assertFalse((root / (draft['backup_set_id'] + '.manifest.json')).exists())

    def test_existing_manifest_is_not_replaced(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            path, _, _ = sealed_fixture(root)
            original = path.read_bytes()
            with self.assertRaisesRegex(ValueError, 'existing manifest'):
                seal(fixture_draft(), root)
            self.assertEqual(path.read_bytes(), original)

    def test_owner_only_directory_and_bounded_manifest_are_required(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            root.chmod(0o755)
            with self.assertRaisesRegex(ValueError, 'owner-only'):
                seal(fixture_draft(), root)
        with self.assertRaises(ValueError):
            read_json(b' ' * (64 * 1024 + 1))
