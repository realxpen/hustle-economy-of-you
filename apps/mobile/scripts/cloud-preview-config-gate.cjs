// Cloud-only, credential-free regression gate for Hustle preview builds.
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const { config: _ignored } = {};
const mobileRoot = path.resolve(__dirname, "..");
const base = require("../app.json").expo;
const build = require("../eas.json").build;
const makeConfig = require("../app.config.js");
const oldVariant = process.env.APP_VARIANT;
const oldProject = process.env.EXPO_PROJECT_ID;
const oldScope = process.env.EXPO_PUBLIC_HUSTLE_RUNTIME_SCOPE;
try {
  delete process.env.EXPO_PUBLIC_HUSTLE_RUNTIME_SCOPE;
  process.env.APP_VARIANT = "preview";
  process.env.EXPO_PROJECT_ID = "eb9df9ee-5f3b-4e90-b9dc-36a770d00c25"; // test fixture only
  const preview = makeConfig({ config: base });
  assert.equal(preview.name, "Hustle Preview");
  assert.equal(preview.owner, "xpen");
  assert.equal(preview.android.package, "com.hustle.economyofyou.preview");
  assert.equal(preview.ios.bundleIdentifier, "com.hustle.economyofyou.preview");
  assert.equal(preview.extra.eas.projectId, "b52b03ef-37f1-4bdf-ab42-5c80e5988ec4");
  process.env.EXPO_PROJECT_ID = "00000000-0000-0000-0000-000000000000";
  const isolated = makeConfig({ config: base });
  assert.equal(isolated.extra.eas.projectId, "b52b03ef-37f1-4bdf-ab42-5c80e5988ec4", "Preview must ignore stale EXPO_PROJECT_ID overrides");
  assert.equal(build.preview.distribution, "internal");
  assert.equal(build.preview.environment, "preview");
  assert.equal(build.preview.android.buildType, "apk");
  assert.equal(build.preview.env.EXPO_PUBLIC_HUSTLE_ENABLE_BOOKING_REQUESTS, "false");
  assert.equal(build.preview.env.EXPO_PUBLIC_HUSTLE_DEMO, "false");
  assert.equal(build.preview.env.EXPO_PUBLIC_HUSTLE_ENABLE_ENQUIRY_MESSAGES, "true");
  assert.equal(build["ios-simulator"].ios.simulator, true);
  process.env.APP_VARIANT = "production";
  delete process.env.EXPO_PROJECT_ID;
  const standard = makeConfig({ config: base });
  assert.equal(standard.name, base.name);
  assert.equal(standard.android.package, base.android.package);
  assert.equal(standard.ios.bundleIdentifier, base.ios.bundleIdentifier);
  const workflow = fs.readFileSync(path.resolve(mobileRoot, "../../.github/workflows/hustle-mobile-eas-preview.yml"), "utf8");
  assert.match(workflow, /workflow_dispatch:/);
  assert.match(workflow, /approved_nonproduction_build/);
  const initWorkflow = fs.readFileSync(path.resolve(mobileRoot, "../../.github/workflows/hustle-expo-project-link.yml"), "utf8");
  assert.match(initWorkflow, /workflow_dispatch:/);
  assert.match(initWorkflow, /confirm_xpen_owner/);
  assert.match(initWorkflow, /eas init --account xpen --non-interactive --json/);
  assert.match(initWorkflow, /WHOAMI=.*eas whoami/);
  assert.match(initWorkflow, /"xpen \(authenticated using EXPO_TOKEN\)"/);
  assert.match(initWorkflow, /case "\$WHOAMI" in/);
  assert.doesNotMatch(initWorkflow, /if \[\[ "\$WHOAMI" != "xpen" \]\]/);
  assert.doesNotMatch(initWorkflow, /eas whoami --non-interactive/);
  assert.match(initWorkflow, /run: npm ci/);
  assert.match(initWorkflow, /secrets.EXPO_TOKEN/);
  assert.match(initWorkflow, /Expo project: https:\/\/expo.dev\/accounts\/xpen\/projects\/hustle/);
  assert.doesNotMatch(initWorkflow, /\n\s+push:/);
  assert.doesNotMatch(initWorkflow, /\n\s+pull_request:/);
  assert.doesNotMatch(initWorkflow, /eas build --platform|eas submit|billing:subscribe/);
  assert.match(workflow, /secrets.EXPO_TOKEN/);
  assert.match(workflow, /EXPO_PROJECT_ID: b52b03ef-37f1-4bdf-ab42-5c80e5988ec4/);
  assert.doesNotMatch(workflow, /vars.EXPO_PROJECT_ID|secrets.EXPO_PROJECT_ID/);
  assert.doesNotMatch(workflow, /e2e-android|e2e-ios|workflow:run|maestro/i);
  assert.deepEqual(Object.keys(build).sort(), ["demo", "ios-simulator", "isolated-staging", "preview"]);
  const stage = build["isolated-staging"];
  assert.equal(stage.extends, "preview");
  assert.equal(stage.env.EXPO_PUBLIC_HUSTLE_AUTH_PROVIDER, "expo-better-auth");
  assert.equal(stage.env.EXPO_PUBLIC_HUSTLE_AUTH_URL, "https://hustle-isolated-staging-api.vercel.app/api/auth");
  assert.equal(stage.env.EXPO_PUBLIC_API_URL, "https://hustle-isolated-staging-api.vercel.app/api/v1");
  assert.equal(stage.env.EXPO_PUBLIC_HUSTLE_DEMO, "false");
  assert.equal(stage.env.EXPO_PUBLIC_HUSTLE_ENABLE_BOOKING_REQUESTS, "false");
  process.env.APP_VARIANT = "preview";
  process.env.EXPO_PUBLIC_HUSTLE_RUNTIME_SCOPE = stage.env.EXPO_PUBLIC_HUSTLE_RUNTIME_SCOPE;
  const connected = makeConfig({ config: base });
  assert.equal(connected.name, "Hustle Staging");
  assert.equal(connected.android.package, "com.hustle.economyofyou.preview.staging");
  assert.equal(connected.ios.bundleIdentifier, "com.hustle.economyofyou.preview.staging");
  assert.equal(connected.scheme, "hustle-preview");
  assert.equal(build.demo.env.EXPO_PUBLIC_HUSTLE_DEMO, "true");
  assert.equal(build.demo.env.EXPO_PUBLIC_HUSTLE_ENABLE_ENQUIRY_MESSAGES, "false");
  assert.equal(build.demo.env.EXPO_PUBLIC_HUSTLE_ENABLE_BOOKING_REQUESTS, "false");
  assert.doesNotMatch(workflow, /--auto-submit/);
  assert.doesNotMatch(workflow, /\n\s+push:/);
  assert.doesNotMatch(workflow, /\n\s+pull_request:/);
  console.log("Hustle cloud preview configuration gate: PASS");
} finally {
  if (oldVariant === undefined) delete process.env.APP_VARIANT;
  else process.env.APP_VARIANT = oldVariant;
  if (oldProject === undefined) delete process.env.EXPO_PROJECT_ID;
  else process.env.EXPO_PROJECT_ID = oldProject;
  if (oldScope === undefined) delete process.env.EXPO_PUBLIC_HUSTLE_RUNTIME_SCOPE;
  else process.env.EXPO_PUBLIC_HUSTLE_RUNTIME_SCOPE = oldScope;
}
